// Regenerates src/server/auth/common-passwords-data.ts from public SecLists files (MIT licensed:
// https://github.com/danielmiessler/SecLists, Passwords/Common-Credentials). Usage:
//   node scripts/build-password-list.mjs <dir-with-downloaded-lists>
// Output has two sections:
//   BASES  – the most common passwords of ANY length (top-10k lists). Used to catch "<common word> + trailing digits/symbols".
//   EXACT  – every entry of length >= 10 from the larger 100k lists (the policy minimum is 10, so shorter ones are rejected by length anyway).
import fs from "node:fs";
import path from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: build-password-list.mjs <dir>");
const read = (f) => fs.readFileSync(path.join(dir, f), "utf8").split(/\r?\n/).map((s) => s.trim().toLowerCase()).filter(Boolean);
const bases = new Set([...read("10k-most-common.txt"), ...read("Pwdb_top-10000.txt")].filter((p) => p.length <= 24));
const big = ["100k-most-used-passwords-NCSC.txt", "Pwdb_top-100000.txt", "xato-net-10-million-passwords-100000.txt"].flatMap(read);
const exact = new Set([...bases, ...big].filter((p) => p.length >= 10 && p.length <= 40 && !/\s/.test(p)));
const clean = (p) => !/[\s`\\$]/.test(p);
const b = [...bases].filter(clean).sort();
const e = [...exact].filter(clean).sort();
const out = `// GENERATED by scripts/build-password-list.mjs from SecLists (MIT). Do not edit by hand.
// bases: ${b.length} common passwords (any length); exact: ${e.length} common passwords of length >= 10.
export const COMMON_BASES = ${JSON.stringify(b.join("\n"))};
export const COMMON_EXACT = ${JSON.stringify(e.join("\n"))};
`;
fs.writeFileSync("src/server/auth/common-passwords-data.ts", out);
console.log({ bases: b.length, exact: e.length, bytes: out.length });
